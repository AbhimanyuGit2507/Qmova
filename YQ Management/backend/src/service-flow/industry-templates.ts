/**
 * Industry Flow Templates — Qmova Blueprint Library
 *
 * PHILOSOPHY: Optimized for realistic physical-world behavior.
 * - Stage 0 bookend: "Booking Verification (QR Scan)" verifies identity/ticket and enforces payment if pending.
 * - Intermediate steps: realistic service actions, smart WAITING_PERIOD steps with real-time countdowns,
 *   and COLLECTION steps with QR scan verification to prevent double redemption.
 * - Final bookend: "Completed Stage" marks visit fulfilled with turnaround metrics.
 *
 * Structure: 14 broad industry verticals covering all common business operations.
 */

export interface StepTemplateData {
  stepOrder: number;
  name: string;
  description?: string;
  type: string;
  trigger: string;
  isOptional?: boolean;
  requiresQrScan?: boolean;
  requiresStaffAction?: boolean;
  deferredByDays?: number;
  deferredByHours?: number;
  entitlementUnit?: string;
  entitlementFormula?: string;
  entitlementFixed?: number;
  allowPartialRedemption?: boolean;
  preventDoubleRedemption?: boolean;
  customerInstruction?: string;
  staffInstruction?: string;
  locationDescription?: string;
  notifyCustomerOnActivation?: boolean;
  outcomeOptions?: string[];
  stepPrice?: number;
  isPriceVariable?: boolean;
  expectedDuration?: number; // In minutes
  bufferDuration?: number; // In minutes
  concurrentSlots?: number;
  orderItems?: any[];
  orderMultiSelect?: boolean;
  orderShowPrices?: boolean;
  orderCatalogId?: string;
}

